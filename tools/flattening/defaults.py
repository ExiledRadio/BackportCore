"""Builds src/main/resources/assets/backportcore/structure/defaults.txt: the default state of every
block of Minecraft 1.16.5 that has properties, as the game's own data report gives it.

A structure file or a processor may name a block without properties ("minecraft:stone_slab"); the
game then means the block's default state (a bottom half). structure.Flattening fills the missing
properties from this table before it picks the 1.12.2 id:meta, so a bare slab is not read as the
first of its Flattening entries (the double slab).

Names are 1.16.5's; Flattening brings them up to today's names when it reads the table, as it does a
1.16.5 structure file's.

Usage (Java 8 runs 1.16.5's data generator):

    java -cp server.jar net.minecraft.data.Main --reports --output <out>
    python -I tools/flattening/defaults.py <out>/reports/blocks.json src/main/resources/assets/backportcore/structure/defaults.txt

Output, one line per block with properties, in the report's (registry) order:

    name[key=value,...]
"""
import json
import sys


def main(report, out):
    with open(report, encoding='utf-8') as f:
        blocks = json.load(f)
    lines = []
    for name, block in blocks.items():
        if not block.get('properties'):
            continue
        default = [s for s in block['states'] if s.get('default')]
        if len(default) != 1:
            raise SystemExit('%s: %d default states' % (name, len(default)))
        props = default[0]['properties']
        lines.append('%s[%s]' % (name, ','.join('%s=%s' % (k, props[k]) for k in sorted(props))))
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('# The default state of every 1.16.5 block with properties, from the game\'s data report.\n')
        f.write('# Generated by tools/flattening/defaults.py. Do not edit.\n')
        for line in lines:
            f.write(line + '\n')
    print('%d blocks' % len(lines))


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
