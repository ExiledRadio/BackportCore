"""Builds src/main/resources/assets/backportcore/structure/item_names.txt: today's name of every 1.12.2 item
whose name or metadata changed, as Minecraft's own data fixers rename a 1.12.2 item stack.

Source: 1.14.4's decompiled data fixers (ForgeGradle's sources jar of a 1.14.4 workspace):
ItemStackDataFlattening (1.13's id+damage to name), the item renames after it in DataFixesManager (1.13's melons
and 1510 renames, 1.14's dyes, signs and stone slab), then the renames since 1.14 listed below by data version.

Usage:

    python -I tools/flattening/items.py <forge-1.14.4-...-sources.jar> src/main/resources/assets/backportcore/structure/item_names.txt

Output, one line per item: ``today legacy meta`` (names without the minecraft: namespace).
"""
import re
import sys
import zipfile

FIXES = 'net/minecraft/util/datafix/fixes/'
LATER = [  # renames since 1.14, in data-version order (Minecraft's ItemRenameFix / ItemStack renames)
    {'grass_path': 'dirt_path'},          # 2680, 1.17
    {'grass': 'short_grass'},             # 3692, 1.20.3
    {'scute': 'turtle_scute'},            # 3814, 1.20.5
    {'chain': 'iron_chain'},              # 4541, 26.1
]


def src(jar, name):
    return jar.read(FIXES + name).decode('utf-8')


def pairs(text):
    return re.findall(r'put\("minecraft:([a-z0-9_.]+)",\s*"minecraft:([a-z0-9_]+)"\)', text)


def main(jar_path, out):
    jar = zipfile.ZipFile(jar_path)
    flat = {}
    for old, new in pairs(src(jar, 'ItemStackDataFlattening.java')):
        name, meta = old.rsplit('.', 1)
        flat[(name, int(meta))] = new
    legacy_names = set(re.findall(r'"minecraft:([a-z0-9_]+)"', src(jar, 'ItemIntIDToString.java')))
    e1510 = src(jar, 'EntityRenameing1510.java')
    item1510 = dict(pairs(e1510[e1510.index('BLOCK_RENAME_MAP'):]))
    chain = [
        {'melon_block': 'melon', 'melon': 'melon_slice', 'speckled_melon': 'glistering_melon_slice'},  # 1490
        item1510,                                                                                       # 1510
        dict(pairs(src(jar, 'DyeRenameMap.java'))),                                                     # 1800
        {'stone_slab': 'smooth_stone_slab', 'sign': 'oak_sign'},                                        # 1802
    ] + LATER

    def rename(n):
        for m in chain:
            n = m.get(n, n)
        return n

    # ItemIntIDToString knows only the numeric-id era's items; the renames' own keys add 1.9-1.12's
    # (chorus_fruit_popped, grass_path). A key 1.12.2 never had (1510's *_bark) is dropped by the game's registry.
    flat_out = set(flat.values())
    for m in chain:
        legacy_names |= set(k for k in m if k not in flat_out)
    rows = {}
    flat_names = set(n for n, _ in flat)
    for (name, meta), new in flat.items():
        rows[(name, meta)] = rename(new)
    for name in legacy_names - flat_names:
        new = rename(name)
        if new != name:
            rows[(name, 0)] = new
    # Two legacy stacks for one name (tallgrass:0 and deadbush both became dead_bush): the item that is only that.
    family = {}
    for (name, meta) in rows:
        family[name] = family.get(name, 0) + 1
    best = {}
    for (name, meta), new in sorted(rows.items()):
        if new not in best or family[name] < family[best[new][0]]:
            best[new] = (name, meta)
    lines = sorted('%s %s %d' % (new, name, meta) for new, (name, meta) in best.items())
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('# Today\'s name of every 1.12.2 item whose name or metadata changed: today legacy meta.\n')
        f.write('# Generated by tools/flattening/items.py from Minecraft\'s data fixers. Do not edit.\n')
        for l in lines:
            f.write(l + '\n')
    print('%d items' % len(lines))


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
