"""Builds the table behind Core's recipe unlocking (recipe/RecipeUnlocks):

  src/main/resources/assets/backportcore/recipes/unlocks.txt

Vanilla unlocks each crafting recipe through an advancement (data/minecraft/advancement/recipes/...): the
recipe is given once the player holds one of a few items, usually its telling ingredient (an iron ingot for
the smithing table, a stick or coal for the campfire). 1.12.2 has the same system, but a backport's recipes
have no such advancements, so its items never showed up in the recipe book. Core reads this table and gives a
backport's recipe at the moment vanilla gives the same one.

Input: a current Minecraft client jar (26.3 when this was written). Only crafting-table recipes are kept.

Lines:
  r <recipe name> <result item> <trigger>[,<trigger>...]     a trigger is an item id or #tag; "-" for none
  t <tag> <item>[,<item>...]                                 every tag a trigger names, fully expanded
All ids are today's, without the "minecraft:" prefix.

Usage:
  python -I tools/recipes/build_unlocks.py <client.jar> <out file>
"""
import json
import sys
import zipfile

CRAFTING = ('minecraft:crafting_shaped', 'minecraft:crafting_shapeless', 'minecraft:crafting_transmute')
ADV = 'data/minecraft/advancement/recipes/'
RECIPE = 'data/minecraft/recipe/'
TAG = 'data/minecraft/tags/item/'


def short(name):
    return name[len('minecraft:'):] if name.startswith('minecraft:') else name


def main(jar, out):
    z = zipfile.ZipFile(jar)
    names = set(z.namelist())

    def tag_items(tag, seen=None):
        seen = seen or set()
        if tag in seen:
            return []
        seen.add(tag)
        path = TAG + tag + '.json'
        if path not in names:
            return []
        items = []
        for v in json.loads(z.read(path))['values']:
            if isinstance(v, dict):
                v = v['id']
            if v.startswith('#'):
                items += tag_items(short(v[1:]), seen)
            else:
                items.append(short(v))
        return items

    rows, tags = [], {}
    for path in sorted(names):
        if not path.startswith(ADV) or not path.endswith('.json'):
            continue
        adv = json.loads(z.read(path))
        rewards = adv.get('rewards', {}).get('recipes', [])
        if len(rewards) != 1:
            continue
        recipe = short(rewards[0])
        rpath = RECIPE + recipe + '.json'
        if rpath not in names:
            continue
        data = json.loads(z.read(rpath))
        if data.get('type') not in CRAFTING:
            continue
        result = data.get('result')
        if isinstance(result, dict):
            result = result.get('id') or result.get('item')
        if not result:
            continue
        result = short(result)
        triggers = []
        for crit in adv['criteria'].values():
            if crit['trigger'] != 'minecraft:inventory_changed':
                continue
            for predicate in crit['conditions'].get('items', []):
                wanted = predicate.get('items')
                for one in ([wanted] if isinstance(wanted, str) else wanted or []):
                    if one.startswith('#'):
                        tag = short(one[1:])
                        tags[tag] = tag_items(tag)
                        one = '#' + tag
                    else:
                        one = short(one)
                    if one not in triggers:
                        triggers.append(one)
        rows.append('r %s %s %s' % (recipe, result, ','.join(triggers) or '-'))

    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('# Generated by tools/recipes/build_unlocks.py from Minecraft 26.3: what unlocks each crafting recipe.\n')
        f.write('# r <recipe> <result> <triggers>   t <tag> <items>   (today\'s ids, "minecraft:" left off)\n')
        for tag in sorted(tags):
            f.write('t %s %s\n' % (tag, ','.join(tags[tag])))
        for row in rows:
            f.write(row + '\n')
    print('%d recipes, %d tags -> %s' % (len(rows), len(tags), out))


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
