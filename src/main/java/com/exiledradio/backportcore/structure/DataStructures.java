    /** What starts in a chunk: the structure, its stub and the random it was made from (assembly draws on). */
    public static final class Choice {
        public final JigsawDef def;
        public final BlockPos position;
        final Piece start;
        final Random random;
        /** {@code PoolAliasLookup}, resolved at the start chunk's corner at the start height. */
        final Map<String, String> aliases;

        Choice(JigsawDef def, BlockPos position, Piece start, Random random, Map<String, String> aliases) {
            this.def = def;
            this.position = position;
            this.start = start;
            this.random = random;
            this.aliases = aliases;
        }
    }

    /** The world's ground and biomes for one start, sampled lazily; loads no chunk. */
    static final class Probe {
        final World world;
        private TerrainHeights heights;
        private boolean heightsAsked;
        private BiomeLocate.Sampler sampler;
        private boolean samplerAsked;

        Probe(World world) {
            this.world = world;
        }

        @Nullable
        private TerrainHeights heights() {
            if (!this.heightsAsked) {
                this.heightsAsked = true;
                this.heights = TerrainHeights.forWorld(this.world);
            }
            return this.heights;
        }

        /** Today's {@code getFirstFreeHeight} of a heightmap type. */
        int height(@Nullable String heightmap, int x, int z) {
            TerrainHeights h = heights();
            boolean floor = "OCEAN_FLOOR_WG".equals(heightmap) || "OCEAN_FLOOR".equals(heightmap);
            if (h != null) {
                return floor ? h.floor(x, z) : h.height(x, z);
            }
            Chunk c = this.world.getChunkProvider().getLoadedChunk(x >> 4, z >> 4);
            return c == null ? this.world.getSeaLevel() : c.getHeightValue(x & 15, z & 15);
        }

        IntBinaryOperator surface() {
            return (x, z) -> height("WORLD_SURFACE_WG", x, z);
        }

        @Nullable
        String biome(int x, int y, int z) {
            if (!this.samplerAsked) {
                this.samplerAsked = true;
                this.sampler = this.world instanceof WorldServer ? BiomeLocate.sampler((WorldServer) this.world) : null;
            }
            if (this.sampler != null) {
                String id = this.sampler.biome(x, y, z);
                if (id != null) {
                    return id;
                }
            }
            Biome b = this.world.getBiomeProvider().getBiome(new BlockPos(x, y, z), null);
            return b == null ? null : BiomeLocate.id(b);
        }

        /** Today's {@code couldStructureExistInColumn}: some quart of the column has one of the biomes. */
        boolean column(Set<String> biomes, int x, int z, int minY, int maxY) {
            // 1.12.2's biomes have one per column; a generator's own sampler may have more.
            if (biomes.contains(biome(x, 64, z))) {
                return true;
            }
            if (this.sampler == null) {
                return false;
            }
            for (int y = minY; y <= maxY; y += 4) {
                if (biomes.contains(biome(x, y, z))) {
                    return true;
                }
            }
            return false;
        }
    }

    /** The world's heights for the start height ({@code WorldGenerationContext}). */
    static HeightProviders.Context context(World world) {
        int min = WorldHeights.minY(world);
        return new HeightProviders.Context(min, WorldHeights.maxYExclusive(world) - min, world.getSeaLevel());
    }

    /**
     * 26.3's choice for a candidate chunk of the set's grid: the frequency and exclusion zone, then (for several
     * structures) weighted draws from {@code setLargeFeatureSeed}'s random, each structure tried with a fresh start
     * random and dropped from the draw when it finds no valid start, until one starts or none is left.
     *
     * @return null where nothing starts; loads no chunk
     */
    @Nullable
    public static Choice choose(SetDef set, World world, int chunkX, int chunkZ) {
        long seed = world.getSeed();
        if (!set.placement.passesRestrictions(seed, chunkX, chunkZ, DataStructures::placementOf)) {
            return null;
        }
        Probe probe = new Probe(world);
        if (set.structures.size() == 1) {
            return tryStart(set.structures.get(0), world, chunkX, chunkZ, probe);
        }
        List<JigsawDef> options = new ArrayList<JigsawDef>(set.structures);
        List<Integer> weights = new ArrayList<Integer>(set.weights);
        Random pick = StructureRandoms.start(seed, chunkX, chunkZ);
        int total = 0;
        for (int w : weights) {
            total += w;
        }
        while (!options.isEmpty()) {
            int choice = pick.nextInt(total);
            int index = 0;
            for (int w : weights) {
                choice -= w;
                if (choice < 0) {
                    break;
                }
                index++;
            }
            Choice c = tryStart(options.get(index), world, chunkX, chunkZ, probe);
            if (c != null) {
                return c;
            }
            options.remove(index);
            total -= weights.remove(index);
        }
        return null;
    }

    /**
     * One structure's own start in a chunk, as 26.3's {@code Structure.generate} finds it (a fresh start random, the
     * stub, the biome at the stub), whatever its set's grid and the other structures of the set say.
     *
     * @return null where it has no valid start there
     */
    @Nullable
    public static Choice startOf(JigsawDef def, World world, int chunkX, int chunkZ) {
        return tryStart(def, world, chunkX, chunkZ, new Probe(world));
    }

    @Nullable
    private static Choice tryStart(JigsawDef def, World world, int chunkX, int chunkZ, Probe probe) {
        if (def.biomes.isEmpty() || !def.dimensions.contains(world.provider.getDimension())) {
            return null;
        }
        Random random = StructureRandoms.start(world.getSeed(), chunkX, chunkZ);
        Choice c = stub(def, world, chunkX, chunkZ, random, probe);
        if (c == null) {
            return null;
        }
        // Structure.findValidGenerationPoint: the biome at the stub's position.
        String biome = probe.biome(c.position.getX(), c.position.getY(), c.position.getZ());
        return biome != null && def.biomes.contains(biome) ? c : null;
    }

    /** {@code JigsawStructure.findGenerationPoint} and {@code JigsawPlacement.addPieces} up to the stub. */
    @Nullable
    static Choice stub(JigsawDef def, World world, int chunkX, int chunkZ, Random random, Probe probe) {
        HeightProviders.Context ctx = context(world);
        int height = def.startHeight.sample(random, ctx);
        BlockPos position = new BlockPos(chunkX << 4, height, chunkZ << 4);
        Map<String, String> aliases = def.aliases.resolve(world.getSeed(), position);
        Rotation rotation = Rotation.values()[random.nextInt(Rotation.values().length)];
        String poolName = ModernJigsaw.full(def.startPool.toString());
        String aliased = aliases.get(poolName);
        // 26.3 takes the alias's pool where it exists, else the start pool itself.
        JigsawPools.Pool pool = aliased == null ? null : JigsawPools.pool(new ResourceLocation(aliased));
        if (pool == null) {
            pool = JigsawPools.pool(new ResourceLocation(poolName));
        }
        if (pool == null || pool.size() == 0) {
            if (REPORTED.add("pool " + def.id)) {
                BackportCore.LOGGER.error("Structure {}: start pool {} is missing or empty.", def.id, poolName);
            }
            return null;
        }
        JigsawElement element = pool.random(random);
        if (element.isEmpty()) {
            return null;
        }
        BlockPos anchored = position;
        if (def.startJigsawName != null) {
            BlockPos anchor = ModernJigsaw.namedJoint(element, position, rotation, random, def.startJigsawName);
            if (anchor == null) {
                if (REPORTED.add("anchor " + def.id)) {
                    BackportCore.LOGGER.error("No starting jigsaw {} found in start pool {}", def.startJigsawName, poolName);
                }
                return null;
            }
            anchored = anchor;
        }
        BlockPos local = anchored.subtract(position);
        BlockPos adjusted = position.subtract(local);
        Piece start = new Piece(element, adjusted, element.groundLevelDelta(), rotation, element.box(adjusted, rotation),
                def.applyWaterlogging);
        StructureBoundingBox box = start.getBoundingBox();
        int centerX = (box.maxX + box.minX) / 2;
        int centerZ = (box.maxZ + box.minZ) / 2;
        int bottomY;
        int minY = ctx.minY;
        int maxY = ctx.minY + ctx.height - 1;
        if (def.heightmap == null) {
            bottomY = adjusted.getY();
        } else {
            if (!probe.column(def.biomes, centerX, centerZ, minY, maxY)) {
                return null;
            }
            bottomY = position.getY() + probe.height(def.heightmap, centerX, centerZ);
        }
        int oldGround = box.minY + start.groundLevelDelta();
        start.offset(0, bottomY - oldGround, 0);
        if (def.paddingBottom != 0 || def.paddingTop != 0) {
            StructureBoundingBox b = start.getBoundingBox();
            if (b.minY < minY + def.paddingBottom || b.maxY > maxY - def.paddingTop) {
                return null;
            }
        }
        int centerY = bottomY + local.getY();
        return new Choice(def, new BlockPos(centerX, centerY, centerZ), start, random, aliases);
    }

    /** The pieces of a choice, the start piece first: {@link ModernJigsaw} with 26.3's rules. */
    public static List<Piece> assemble(Choice c, World world) {
        JigsawDef def = c.def;
        HeightProviders.Context ctx = context(world);
        BlockPos p = c.position;
        int h = def.maxHorizontal;
        int v = def.maxVertical;
        int low = Math.max(p.getY() - v, ctx.minY + def.paddingBottom);
        int highExclusive = Math.min(p.getY() + v + 1, ctx.minY + ctx.height - def.paddingTop);
        StructureBoundingBox bounds = new StructureBoundingBox(p.getX() - h, low, p.getZ() - h, p.getX() + h, highExclusive - 1, p.getZ() + h);
        return ModernJigsaw.<Piece>of((e, pos, g, r, b) -> new Piece(e, pos, g, r, b, def.applyWaterlogging))
                .maxDepth(def.size).expansionHack(def.expansionHack).priorities(true).namelessFeatures(true)
                .aliases(c.aliases).surface(new Probe(world).surface())
                .assemble(c.start, bounds, c.random);
    }

