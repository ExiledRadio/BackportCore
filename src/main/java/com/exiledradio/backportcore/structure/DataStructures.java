    /** Reads and registers every structure set. Load complete, after every backport registered its own structures. */
    public static synchronized void load() {
        readVanillaSets();
        if (!CoreConfig.structure.dataStructures) {
            BackportCore.LOGGER.info("Data-driven structures are off (structure.dataStructures).");
            return;
        }
        DataPacks.scanDropIns();
        JigsawPools.clearCache();
        DataTags.clear();
        Map<ResourceLocation, String> structureFiles = DataPacks.list("worldgen/structure", ".json");
        Map<ResourceLocation, String> setFiles = DataPacks.list("worldgen/structure_set", ".json");
        Set<String> family = new HashSet<String>(StructureLocate.ids());
        for (Map.Entry<ResourceLocation, String> e : setFiles.entrySet()) {
            ResourceLocation setId = e.getKey();
            if (blacklisted(setId.toString())) {
                skip(setId + ": blacklisted (structure.blacklist)");
                continue;
            }
            JsonElement json = DataPacks.json(e.getValue());
            if (json == null || !json.isJsonObject()) {
                skip(setId + ": unreadable");
                continue;
            }
            JsonObject set = json.getAsJsonObject();
            DataPlacement placement;
            try {
                placement = DataPlacement.read(set.getAsJsonObject("placement"));
            } catch (UnsupportedOperationException ex) {
                skip(setId + ": placement " + ex.getMessage() + " is not supported");
                continue;
            } catch (RuntimeException ex) {
                skip(setId + ": placement could not be read: " + ex);
                continue;
            }
            List<JigsawDef> list = new ArrayList<JigsawDef>();
            List<Integer> weights = new ArrayList<Integer>();
            for (JsonElement entry : set.getAsJsonArray("structures")) {
                JsonObject o = entry.getAsJsonObject();
                ResourceLocation sid = new ResourceLocation(o.get("structure").getAsString());
                int weight = o.has("weight") ? o.get("weight").getAsInt() : 1;
                JigsawDef def = structure(sid, structureFiles, family);
                if (def != null && weight > 0) {
                    list.add(def);
                    weights.add(weight);
                }
            }
            if (list.isEmpty()) {
                skip(setId + ": no structure of it is generated here");
                continue;
            }
            SetDef def = new SetDef(setId, placement, list, weights);
            SETS.put(setId, def);
            register(def);
        }
        tagStructures();
        BackportCore.LOGGER.info("Data-driven structures: {} sets ({} structures) loaded, {} skipped.", SETS.size(), STRUCTURES.size(),
                SKIPPED.size());
    }

    @Nullable
    private static JigsawDef structure(ResourceLocation id, Map<ResourceLocation, String> files, Set<String> family) {
        JigsawDef known = STRUCTURES.get(id);
        if (known != null) {
            return known;
        }
        String full = id.toString();
        if (blacklisted(full)) {
            skip(full + ": blacklisted (structure.blacklist)");
            return null;
        }
        if (family.contains(full) || Structures.has(full)
                || ("minecraft".equals(id.getNamespace()) && Structures.has(id.getPath()))) {
            skip(full + ": already generated by a backport or 1.12.2");
            return null;
        }
        String path = files.get(id);
        JsonElement json = path == null ? null : DataPacks.json(path);
        if (json == null || !json.isJsonObject()) {
            skip(full + ": no structure file");
            return null;
        }
        JsonObject s = json.getAsJsonObject();
        String type = ModernPalette.full(s.has("type") ? s.get("type").getAsString() : "");
        if (!"minecraft:jigsaw".equals(type)) {
            skip(full + ": structure type " + type + " is not data-driven");
            return null;
        }
        try {
            JigsawDef def = new JigsawDef(id, s);
            STRUCTURES.put(id, def);
            return def;
        } catch (RuntimeException ex) {
            BackportCore.LOGGER.error("Structure {} could not be read.", id, ex);
            skip(full + ": could not be read: " + ex);
            return null;
        }
    }

    private static void skip(String why) {
        SKIPPED.add(why);
        BackportCore.LOGGER.info("Data-driven structures: skipped {}", why);
    }

    /** @return true if the config's blacklist names the id (or {@code namespace:*}) */
    public static boolean blacklisted(String id) {
        String full = StructureLocate.normalize(id);
        String ns = full.substring(0, full.indexOf(':'));
        for (String entry : CoreConfig.structure.blacklist) {
            String b = entry.trim();
            if (b.isEmpty()) {
                continue;
            }
            if (b.endsWith(":*") ? ns.equals(b.substring(0, b.length() - 2).toLowerCase(Locale.ROOT)) : full.equals(StructureLocate.normalize(b))) {
                return true;
            }
        }
        return false;
    }

    private static void readVanillaSets() {
        if (!VANILLA_SETS.isEmpty()) {
            return;
        }
        for (String name : new String[] {"ancient_cities", "buried_treasures", "desert_pyramids", "end_cities", "igloos",
                "jungle_temples", "nether_complexes", "nether_fossils", "ocean_monuments", "ocean_ruins", "pillager_outposts",
                "ruined_portals", "shipwrecks", "swamp_huts", "trail_ruins", "trial_chambers", "villages", "woodland_mansions",
                "abandoned_camp", "mineshafts"}) {
            JsonElement json = DataPacks.json("assets/backportcore/vanilla_structure_sets/" + name + ".json");
            if (json == null) {
                continue;
            }
            try {
                VANILLA_SETS.put(new ResourceLocation("minecraft", name), DataPlacement.read(json.getAsJsonObject().getAsJsonObject("placement")));
            } catch (RuntimeException e) {
                BackportCore.LOGGER.debug("Vanilla structure set {} is not a random spread.", name);
            }
        }
    }

    private static void register(SetDef set) {
        ScatteredStructure.register(set.kind, world -> set.dimensions.contains(world.provider.getDimension()) ? new Generator(set) : null);
        String[] ids = new String[set.structures.size()];
        for (int i = 0; i < ids.length; i++) {
            ids[i] = set.structures.get(i).id.toString();
        }
        StructureLocate.scattered(set.id.toString(), set.kind, (world, structure, x, z) -> {
            Choice c = structure instanceof Generator ? ((Generator) structure).choose(world, x, z) : null;
            return c == null ? null : c.def.id.toString();
        }, set.placement.offsetX(), set.placement.offsetY(), set.placement.offsetZ(), ids);
        if (set.structures.size() > 1) {
            for (JigsawDef def : set.structures) {
                final String id = def.id.toString();
                Structures.register(id, (world, from, radius) -> {
                    ScatteredStructure s = ScatteredStructure.of(world, set.kind);
                    if (!(s instanceof Generator)) {
                        return null;
                    }
                    Generator g = (Generator) s;
                    ChunkPos c = g.placement().nearest(world.getSeed(), from, radius, p -> {
                        Choice choice = g.locatableAt(world, p.x, p.z) ? g.choose(world, p.x, p.z) : null;
                        return choice != null && choice.def.id.toString().equals(id);
                    });
                    return c == null ? null : new BlockPos((c.x << 4) + 8, from.getY(), (c.z << 4) + 8);
                });
            }
        }
        if (set.adaptation != TerrainAdaptation.Kind.NONE) {
            TerrainAdaptation.register(set.kind, set.adaptation, (world, cx, cz, out) -> {
                ScatteredStructure s = ScatteredStructure.of(world, set.kind);
                if (s instanceof Generator) {
                    ((Generator) s).startsNear(world, cx, cz, out);
                }
            });
        }
        for (JigsawDef def : set.structures) {
            if (!def.spawns.isEmpty() && !spawnsRegistered) {
                spawnsRegistered = true;
                MinecraftForge.EVENT_BUS.register(new Spawns());
            }
        }
        BackportCore.LOGGER.info("Data-driven structure set {}: {} in dimensions {}.", set.id, set.structures, set.dimensions);
    }

    /** Structure tags ({@code data/<ns>/tags/worldgen/structure}) for {@code /locate structure #tag}, with the loaded members. */
    private static void tagStructures() {
        Set<String> loaded = new HashSet<String>();
        for (ResourceLocation id : STRUCTURES.keySet()) {
            loaded.add(id.toString());
        }
        for (ResourceLocation tag : DataPacks.list("tags/worldgen/structure", ".json").keySet()) {
            List<String> members = new ArrayList<String>();
            for (String m : DataTags.members("worldgen/structure", tag.toString())) {
                if (loaded.contains(m)) {
                    members.add(m);
                }
            }
            if (!members.isEmpty()) {
                StructureLocate.tag(tag.toString(), members.toArray(new String[0]));
            }
        }
    }

    /** 1.12.2's dimensions a structure's biomes are in: the nether, the end, else the overworld. */
    static Set<Integer> dimensionsOf(Set<String> biomes) {
        Set<String> nether = new HashSet<String>(Arrays.asList("minecraft:nether_wastes", "minecraft:crimson_forest",
                "minecraft:warped_forest", "minecraft:soul_sand_valley", "minecraft:basalt_deltas"));
        Set<String> end = new HashSet<String>(Arrays.asList("minecraft:the_end", "minecraft:end_highlands", "minecraft:end_midlands",
                "minecraft:small_end_islands", "minecraft:end_barrens"));
        Set<Integer> out = new LinkedHashSet<Integer>();
        for (String b : biomes) {
            out.add(nether.contains(b) ? -1 : end.contains(b) ? 1 : 0);
        }
        if (out.isEmpty()) {
            out.add(0);
        }
        return out;
    }

