    // ---- what is read

    /** One {@code minecraft:jigsaw} structure: today's {@code JigsawStructure} and its {@code StructureSettings}. */
    public static final class JigsawDef {
        public final ResourceLocation id;
        /** Today's biome ids the structure starts in (the tag resolved). */
        public final Set<String> biomes;
        public final TerrainAdaptation.Kind adaptation;
        public final ResourceLocation startPool;
        @Nullable
        public final String startJigsawName;
        public final int size;
        public final HeightProviders.Height startHeight;
        public final boolean expansionHack;
        /** {@code project_start_to_heightmap}, upper case, or null. */
        @Nullable
        public final String heightmap;
        public final int maxHorizontal;
        public final int maxVertical;
        public final ModernJigsaw.PoolAliases aliases;
        public final int paddingBottom;
        public final int paddingTop;
        public final boolean applyWaterlogging;
        /** 1.12.2 dimensions it can start in: 0, -1, 1. */
        public final Set<Integer> dimensions;
        /** {@code spawn_overrides} by 1.12.2's creature type. */
        final Map<EnumCreatureType, SpawnOverride> spawns;

        JigsawDef(ResourceLocation id, JsonObject s) {
            this.id = id;
            this.biomes = Collections.unmodifiableSet(DataTags.biomes(s.get("biomes")));
            this.adaptation = s.has("terrain_adaptation")
                    ? TerrainAdaptation.Kind.valueOf(s.get("terrain_adaptation").getAsString().toUpperCase(Locale.ROOT))
                    : TerrainAdaptation.Kind.NONE;
            this.startPool = new ResourceLocation(s.get("start_pool").getAsString());
            this.startJigsawName = s.has("start_jigsaw_name") ? ModernJigsaw.full(s.get("start_jigsaw_name").getAsString()) : null;
            this.size = s.get("size").getAsInt();
            if (this.size < 0 || this.size > 20) {
                throw new IllegalArgumentException("size " + this.size + " is outside 0 to 20");
            }
            this.startHeight = HeightProviders.read(s.get("start_height"));
            this.expansionHack = s.has("use_expansion_hack") && s.get("use_expansion_hack").getAsBoolean();
            this.heightmap = s.has("project_start_to_heightmap") ? s.get("project_start_to_heightmap").getAsString().toUpperCase(Locale.ROOT) : null;
            JsonElement d = s.get("max_distance_from_center");
            if (d == null || d.isJsonPrimitive()) {
                this.maxHorizontal = d == null ? 80 : d.getAsInt();
                this.maxVertical = this.maxHorizontal;
            } else {
                JsonObject o = d.getAsJsonObject();
                this.maxHorizontal = o.get("horizontal").getAsInt();
                // DimensionType.Y_SIZE
                this.maxVertical = o.has("vertical") ? o.get("vertical").getAsInt() : 4064;
            }
            int edge = this.adaptation == TerrainAdaptation.Kind.NONE ? 0 : 12;
            if (this.maxHorizontal + edge > MAX_RANGE) {
                throw new IllegalArgumentException("Horizontal structure size including terrain adaptation must not exceed 128");
            }
            this.aliases = ModernJigsaw.PoolAliases.read(s.has("pool_aliases") ? s.getAsJsonArray("pool_aliases") : null);
            JsonElement pad = s.get("dimension_padding");
            if (pad == null) {
                this.paddingBottom = 0;
                this.paddingTop = 0;
            } else if (pad.isJsonPrimitive()) {
                this.paddingBottom = pad.getAsInt();
                this.paddingTop = pad.getAsInt();
            } else {
                JsonObject o = pad.getAsJsonObject();
                this.paddingBottom = o.has("bottom") ? o.get("bottom").getAsInt() : 0;
                this.paddingTop = o.has("top") ? o.get("top").getAsInt() : 0;
            }
            this.applyWaterlogging = !s.has("liquid_settings") || !"ignore_waterlogging".equals(s.get("liquid_settings").getAsString());
            this.dimensions = Collections.unmodifiableSet(dimensionsOf(this.biomes));
            this.spawns = SpawnOverride.read(id, s.has("spawn_overrides") ? s.getAsJsonObject("spawn_overrides") : null);
        }

        @Override
        public String toString() {
            return this.id.toString();
        }
    }

    /** One structure set: its placement and its weighted structures, in file order. */
    public static final class SetDef {
        public final ResourceLocation id;
        public final DataPlacement placement;
        public final List<JigsawDef> structures;
        public final List<Integer> weights;
        /** The {@link ScatteredStructure} kind: the one structure's id, or the set's id. */
        public final String kind;
        final String saveName;
        final Set<Integer> dimensions;
        final TerrainAdaptation.Kind adaptation;
        final int range;

        SetDef(ResourceLocation id, DataPlacement placement, List<JigsawDef> structures, List<Integer> weights) {
            this.id = id;
            this.placement = placement;
            this.structures = Collections.unmodifiableList(structures);
            this.weights = Collections.unmodifiableList(weights);
            this.kind = structures.size() == 1 ? structures.get(0).id.toString() : id.toString();
            this.saveName = START_NAME + "_" + id.toString().replaceAll("[^a-z0-9_.-]", "_");
            Set<Integer> dims = new LinkedHashSet<Integer>();
            TerrainAdaptation.Kind adaptation = TerrainAdaptation.Kind.NONE;
            int reach = 0;
            for (JigsawDef s : structures) {
                dims.addAll(s.dimensions);
                if (adaptation == TerrainAdaptation.Kind.NONE) {
                    adaptation = s.adaptation;
                }
                reach = Math.max(reach, s.maxHorizontal);
            }
            this.dimensions = dims;
            this.adaptation = adaptation;
            // Chunks from the start chunk a layout can reach: its box, plus a start piece's own size beyond it.
            this.range = Math.min(9, Math.max(2, (reach + 15) / 16 + 1));
        }

        /** @return true if a structure of the set overrides this creature type's spawns */
        boolean overrides(EnumCreatureType type) {
            for (JigsawDef s : this.structures) {
                if (s.spawns.containsKey(type)) {
                    return true;
                }
            }
            return false;
        }

        @Override
        public String toString() {
            return this.id.toString();
        }
    }

    /** @return every structure loaded, by id */
    public static synchronized Map<ResourceLocation, JigsawDef> structures() {
        return new LinkedHashMap<ResourceLocation, JigsawDef>(STRUCTURES);
    }

    /** @return every structure set loaded, by id */
    public static synchronized Map<ResourceLocation, SetDef> sets() {
        return new LinkedHashMap<ResourceLocation, SetDef>(SETS);
    }

    /** @return what was read and left out, "id: why", for tests and the log */
    public static synchronized List<String> skipped() {
        return new ArrayList<String>(SKIPPED);
    }

    /** @return the placement of a set by id: a loaded set's, else 26.3's vanilla set's, else null */
    @Nullable
    public static synchronized DataPlacement placementOf(ResourceLocation set) {
        SetDef def = SETS.get(set);
        if (def != null) {
            return def.placement;
        }
        return VANILLA_SETS.get(set);
    }

