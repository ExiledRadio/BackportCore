    /** One set's structure in one world: Core's scattered driver lays it out and builds it. */
    public static final class Generator extends ScatteredStructure {
        final SetDef set;
        /** Candidate chunks found to start nothing, so each populate within range does not ask again. */
        private final Map<Long, Boolean> nothing = new LinkedHashMap<Long, Boolean>(256, 0.75F, true) {
            private static final long serialVersionUID = 1L;

            @Override
            protected boolean removeEldestEntry(Map.Entry<Long, Boolean> eldest) {
                return size() > 4096;
            }
        };
        private boolean building;

        Generator(SetDef set) {
            super(set.saveName, set.placement.grid());
            this.set = set;
            this.range = set.range;
        }

        public SetDef set() {
            return this.set;
        }

        @Nullable
        public Choice choose(World world, int chunkX, int chunkZ) {
            long key = ChunkPos.asLong(chunkX, chunkZ);
            synchronized (this.nothing) {
                if (this.nothing.containsKey(key)) {
                    return null;
                }
            }
            Choice c = DataStructures.choose(this.set, world, chunkX, chunkZ);
            if (c == null) {
                synchronized (this.nothing) {
                    this.nothing.put(key, Boolean.TRUE);
                }
            }
            return c;
        }

        @Override
        protected boolean canStartAt(World world, int chunkX, int chunkZ) {
            return choose(world, chunkX, chunkZ) != null;
        }

        @Nullable
        @Override
        public String variantAt(World world, int chunkX, int chunkZ) {
            Choice c = this.set.structures.size() > 1 ? choose(world, chunkX, chunkZ) : null;
            return c == null ? null : c.def.id.getPath();
        }

        @Override
        protected StructureStart getStructureStart(int chunkX, int chunkZ) {
            return new Start(this, this.world, chunkX, chunkZ);
        }

        @Override
        public synchronized boolean generateStructure(World world, Random random, ChunkPos chunk) {
            this.building = true;
            try {
                return super.generateStructure(world, random, chunk);
            } finally {
                this.building = false;
            }
        }

        /** @return the start laid out in a chunk, laying it out if it is not yet; null where none starts */
        @Nullable
        public Start startAt(World world, int chunkX, int chunkZ) {
            this.world = world;
            initializeStructureData(world);
            long key = ChunkPos.asLong(chunkX, chunkZ);
            StructureStart start = this.structureMap.get(key);
            if (start == null && canSpawnStructureAtCoords(chunkX, chunkZ)) {
                generate(world, chunkX, chunkZ, null);
                start = this.structureMap.get(key);
            }
            return start instanceof Start ? (Start) start : null;
        }

        /** @return every start of this set laid out in this world so far */
        public List<Start> laidOut(World world) {
            this.world = world;
            initializeStructureData(world);
            List<Start> out = new ArrayList<Start>();
            for (StructureStart s : this.structureMap.values()) {
                if (s instanceof Start) {
                    out.add((Start) s);
                }
            }
            return out;
        }

        /** Core's terrain adaptation planner. Loads no chunks. */
        void startsNear(World world, int cx, int cz, Consumer<StructureStart> out) {
            this.world = world;
            initializeStructureData(world);
            int reach = this.range;
            int s = placement().spacing();
            for (int gx = Math.floorDiv(cx - reach, s); gx <= Math.floorDiv(cx + reach, s); gx++) {
                for (int gz = Math.floorDiv(cz - reach, s); gz <= Math.floorDiv(cz + reach, s); gz++) {
                    ChunkPos c = placement().candidate(world.getSeed(), gx * s, gz * s);
                    if (Math.abs(c.x - cx) > reach || Math.abs(c.z - cz) > reach) {
                        continue;
                    }
                    long key = ChunkPos.asLong(c.x, c.z);
                    StructureStart start = this.structureMap.get(key);
                    if (start == null) {
                        if (!canSpawnStructureAtCoords(c.x, c.z)) {
                            continue;
                        }
                        if (this.building) {
                            start = getStructureStart(c.x, c.z);
                        } else {
                            generate(world, c.x, c.z, null);
                            start = this.structureMap.get(key);
                        }
                    }
                    if (start != null && start.isSizeableStructure() && reaches(start.getBoundingBox(), cx, cz)) {
                        out.accept(start);
                    }
                }
            }
        }

        static boolean reaches(StructureBoundingBox b, int cx, int cz) {
            int x = cx << 4;
            int z = cz << 4;
            return b != null && b.maxX + 12 >= x && b.minX - 12 <= x + 15 && b.maxZ + 12 >= z && b.minZ - 12 <= z + 15;
        }

        /** The spawn override at a position, or null. */
        @Nullable
        SpawnOverride overrideAt(World world, BlockPos pos, EnumCreatureType type) {
            this.world = world;
            initializeStructureData(world);
            for (StructureStart s : this.structureMap.values()) {
                if (!(s instanceof Start) || !s.isSizeableStructure() || !s.getBoundingBox().isVecInside(pos)) {
                    continue;
                }
                JigsawDef def = STRUCTURES.get(new ResourceLocation(((Start) s).structure));
                SpawnOverride o = def == null ? null : def.spawns.get(type);
                if (o == null) {
                    continue;
                }
                if (!o.piece) {
                    return o;
                }
                for (StructureComponent c : s.getComponents()) {
                    if (c.getBoundingBox().isVecInside(pos)) {
                        return o;
                    }
                }
            }
            return null;
        }
    }

    /** A start of a data-driven structure, saved with its structure's id. */
    public static final class Start extends StructureStart {
        String structure = "";

        /** For loading. */
        public Start() {
        }

        Start(Generator generator, World world, int chunkX, int chunkZ) {
            super(chunkX, chunkZ);
            Choice c = generator.choose(world, chunkX, chunkZ);
            if (c != null) {
                this.structure = c.def.id.toString();
                this.components.addAll(assemble(c, world));
            }
            updateBoundingBox();
        }

        /** @return the structure's id ({@code namespace:path}) */
        public String structure() {
            return this.structure;
        }

        /** @return the pieces, start piece first */
        public List<StructureComponent> pieces() {
            return this.components;
        }

        @Override
        public boolean isSizeableStructure() {
            return !this.components.isEmpty();
        }

        @Override
        public void writeToNBT(NBTTagCompound tag) {
            super.writeToNBT(tag);
            tag.setString("structure", this.structure);
        }

        @Override
        public void readFromNBT(NBTTagCompound tag) {
            super.readFromNBT(tag);
            this.structure = tag.getString("structure");
        }

        @Override
        public void generateStructure(World world, Random random, StructureBoundingBox box) {
            // 1.12.2's MapGenStructure clips each chunk to y 1-512; a world that goes below 0 builds its whole height.
            StructureBoundingBox chunk = new StructureBoundingBox(box.minX, Math.min(box.minY, WorldHeights.minY(world)), box.minZ,
                    box.maxX, box.maxY, box.maxZ);
            super.generateStructure(world, random, chunk);
        }
    }

    /** A piece of a data-driven structure: today's {@code PoolElementStructurePiece}, with its junctions and liquid settings. */
    public static class Piece extends JigsawPiece implements TerrainAdaptation.AdaptingPiece, ModernJigsaw.Joined {

        private int[] junctions = new int[0];
        private boolean waterlogging = true;

        /** For loading. */
        public Piece() {
        }

        public Piece(JigsawElement element, BlockPos position, int groundLevelDelta, Rotation rotation, StructureBoundingBox box,
                     boolean applyWaterlogging) {
            super(element, position, groundLevelDelta, rotation, box);
            this.waterlogging = applyWaterlogging;
        }

        @Override
        protected boolean applyWaterlogging() {
            return this.waterlogging;
        }

        @Override
        public void addJunction(int x, int groundY, int z) {
            int n = this.junctions.length;
            this.junctions = Arrays.copyOf(this.junctions, n + 3);
            this.junctions[n] = x;
            this.junctions[n + 1] = groundY;
            this.junctions[n + 2] = z;
        }

        @Override
        public boolean rigid() {
            return this.element == null || this.element.rigid();
        }

        @Override
        public int[] junctions() {
            return this.junctions.clone();
        }

        @Override
        public void offset(int x, int y, int z) {
            super.offset(x, y, z);
            this.pivot = this.pivot.add(x, y, z);
            for (int n = 0; n < this.junctions.length; n += 3) {
                this.junctions[n] += x;
                this.junctions[n + 1] += y;
                this.junctions[n + 2] += z;
            }
        }

        @Override
        protected void writeStructureToNBT(NBTTagCompound tag) {
            super.writeStructureToNBT(tag);
            tag.setIntArray("junctions", this.junctions);
            tag.setBoolean("waterlogging", this.waterlogging);
        }

        @Override
        protected void readStructureFromNBT(NBTTagCompound tag, TemplateManager manager) {
            super.readStructureFromNBT(tag, manager);
            int[] j = tag.getIntArray("junctions");
            this.junctions = j.length % 3 == 0 ? j : new int[0];
            this.waterlogging = !tag.hasKey("waterlogging") || tag.getBoolean("waterlogging");
        }
    }

    // ---- spawn overrides

    /** One category of a structure's {@code spawn_overrides}: inside its pieces (or its whole box) only these spawn. */
    static final class SpawnOverride {
        final boolean piece;
        final List<Biome.SpawnListEntry> spawns;

        SpawnOverride(boolean piece, List<Biome.SpawnListEntry> spawns) {
            this.piece = piece;
            this.spawns = spawns;
        }

        @SuppressWarnings("unchecked")
        static Map<EnumCreatureType, SpawnOverride> read(ResourceLocation id, @Nullable JsonObject o) {
            Map<EnumCreatureType, SpawnOverride> out = new EnumMap<EnumCreatureType, SpawnOverride>(EnumCreatureType.class);
            if (o == null) {
                return out;
            }
            for (Map.Entry<String, JsonElement> e : o.entrySet()) {
                EnumCreatureType type;
                switch (e.getKey()) {
                    case "monster": type = EnumCreatureType.MONSTER; break;
                    case "creature": type = EnumCreatureType.CREATURE; break;
                    case "ambient": type = EnumCreatureType.AMBIENT; break;
                    case "water_creature": type = EnumCreatureType.WATER_CREATURE; break;
                    default: continue; // 1.12.2 has no axolotls, water_ambient, underground_water_creature or misc
                }
                JsonObject c = e.getValue().getAsJsonObject();
                boolean piece = !"full".equals(c.has("bounding_box") ? c.get("bounding_box").getAsString() : "piece");
                List<Biome.SpawnListEntry> list = new ArrayList<Biome.SpawnListEntry>();
                for (JsonElement s : c.getAsJsonArray("spawns")) {
                    JsonObject so = s.getAsJsonObject();
                    String mob = ModernPalette.entity(ModernPalette.full(so.get("type").getAsString()));
                    Class<?> cls = EntityList.getClass(new ResourceLocation(mob));
                    if (cls == null || !EntityLiving.class.isAssignableFrom(cls)) {
                        BackportCore.LOGGER.warn("Structure {}: spawn override mob {} is not in this game; it is left out.", id, mob);
                        continue;
                    }
                    list.add(new Biome.SpawnListEntry((Class<? extends EntityLiving>) cls, so.get("weight").getAsInt(),
                            so.has("minCount") ? so.get("minCount").getAsInt() : 1, so.has("maxCount") ? so.get("maxCount").getAsInt() : 1));
                }
                out.put(type, new SpawnOverride(piece, list));
            }
            return out;
        }
    }

    /** Today's {@code spawn_overrides}: the list of mobs that may spawn inside a structure replaces the biome's. */
    public static final class Spawns {
        @SubscribeEvent
        public void potentialSpawns(WorldEvent.PotentialSpawns event) {
            World world = event.getWorld();
            if (world.isRemote) {
                return;
            }
            List<SetDef> sets;
            synchronized (DataStructures.class) {
                sets = new ArrayList<SetDef>(SETS.values());
            }
            for (SetDef set : sets) {
                if (!set.overrides(event.getType())) {
                    continue;
                }
                ScatteredStructure s = ScatteredStructure.of(world, set.kind);
                if (!(s instanceof Generator)) {
                    continue;
                }
                SpawnOverride o = ((Generator) s).overrideAt(world, event.getPos(), event.getType());
                if (o != null) {
                    event.getList().clear();
                    event.getList().addAll(o.spawns);
                    return;
                }
            }
        }
    }
